#!/usr/bin/env python3
"""src/flags.h: a 16x12 flag for each country of cty.dat, by its primary prefix.
cty.dat (AD1C) gives the primary prefix of each entity; k0swe's dxcc.json (MIT) its ISO
country code; flags_dir holds flagcdn.com's 20 px PNGs (<iso>.png, flags are public domain).

  flags_gen.py cty.dat dxcc.json flags_dir --codes   ISO codes needed, one a line
  flags_gen.py cty.dat dxcc.json flags_dir > src/flags.h
"""
import json
import re
import sys

W, H = 16, 12
MANUAL = {'ZB': 'gi', 'OJ0': 'fi'}  # not found in dxcc.json
FILE = {'xi': 'gb-nir'}             # flagcdn's name for it


def cty_prefixes(path):
    out = []
    for line in open(path, encoding='latin-1'):
        if line[:1] not in (' ', '\t') and ':' in line:
            f = [x.strip() for x in line.split(':')]
            if len(f) >= 8:
                out.append(f[7].lstrip('*'))   # primary prefix; * = not DXCC (WAE)
    return out


def iso_of(prefixes, dxcc):
    ents = [e for e in json.load(open(dxcc))['dxcc']
            if not e.get('deleted') and e.get('countryCode') and e['countryCode'] != 'ZZ']
    table = {}
    for p in prefixes:
        base = p.split('/')[0]
        # the prefix listed as it is first; else a likely call of it ("I" -> I1ABC, "VK" -> VK1ABC)
        hit = [e for e in ents if base in e['prefix'].split(',')]
        if not hit:
            call = base + ('ABC' if base[-1].isdigit() else '1ABC')
            for e in ents:
                try:
                    if re.match(e['prefixRegex'], call):
                        hit = [e]
                        break
                except re.error:
                    pass
        if hit:
            table[p] = hit[0]['countryCode'].lower()
        elif base in MANUAL:
            table[p] = MANUAL[base]
    return table


def main():
    cty, dxcc, fdir = sys.argv[1:4]
    table = iso_of(cty_prefixes(cty), dxcc)
    if '--codes' in sys.argv:
        print('\n'.join(sorted(set(table.values()))))
        return
    from PIL import Image
    flags, rows = {}, []
    for p, iso in sorted(table.items()):
        if iso not in flags:
            try:
                img = Image.open('%s/%s.png' % (fdir, FILE.get(iso, iso))).convert('RGB').resize((W, H), Image.LANCZOS)
            except OSError:
                continue
            flags[iso] = (len(flags), img)
        rows.append((p, flags[iso][0]))
    print('/* Generated by tools/flags_gen.py: 16x12 flags (flagcdn.com, public domain) by the')
    print(' * primary prefix of cty.dat (AD1C), ISO codes from k0swe/dxcc-json (MIT). Do not edit. */')
    print('#pragma once\n\n#include <stdint.h>\n')
    print('#define FLAG_W %d\n#define FLAG_H %d\n' % (W, H))
    print('static const uint8_t flag_px[][FLAG_W * FLAG_H * 3] = {  /* RGB */')
    for iso, (i, img) in sorted(flags.items(), key=lambda x: x[1][0]):
        data = img.tobytes()
        print('    { /* %s */' % iso)
        for k in range(0, len(data), 24):
            print('        ' + ','.join(str(b) for b in data[k:k + 24]) + ',')
        print('    },')
    print('};\n')
    print('static const struct { const char *prefix; uint16_t flag; } flag_of[] = {  /* by prefix */')
    for p, i in rows:
        print('    {"%s", %d},' % (p, i))
    print('};')


main()
