#!/usr/bin/env python3
"""src/world_map.h from Natural Earth 110m land (public domain): coastline rings,
simplified, in tenths of a degree. Usage: world_map_gen.py ne_110m_land.geojson > src/world_map.h"""
import json
import sys

TOL = 0.4       # degrees, Douglas-Peucker
MIN_SPAN = 1.5  # degrees: smaller islands are left out


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    dx, dy = x1 - x0, y1 - y0
    n = (dx * dx + dy * dy) ** 0.5
    best, idx = -1.0, 0
    for i in range(1, len(pts) - 1):
        x, y = pts[i]
        d = abs(dy * x - dx * y + x1 * y0 - y1 * x0) / n if n else ((x - x0) ** 2 + (y - y0) ** 2) ** 0.5
        if d > best:
            best, idx = d, i
    if best <= tol:
        return [pts[0], pts[-1]]
    return dp(pts[:idx + 1], tol)[:-1] + dp(pts[idx:], tol)


rings = []
for f in json.load(open(sys.argv[1]))['features']:
    g = f['geometry']
    polys = [g['coordinates']] if g['type'] == 'Polygon' else g['coordinates']
    for poly in polys:
        ring = poly[0]  # outer ring: lakes are not drawn
        xs, ys = [p[0] for p in ring], [p[1] for p in ring]
        if max(xs) - min(xs) < MIN_SPAN and max(ys) - min(ys) < MIN_SPAN:
            continue
        r = dp(ring, TOL)
        if len(r) >= 4:
            rings.append([(round(x * 10), round(y * 10)) for x, y in r])

pts = [p for r in rings for p in r]
print('/* Generated by tools/world_map_gen.py from Natural Earth 110m land (public domain):')
print(' * coastline rings, lon and lat in tenths of a degree. Do not edit. */')
print('#pragma once\n\n#include <stdint.h>\n')
print('static const int16_t world_map_pts[][2] = {')
for i in range(0, len(pts), 8):
    print('    ' + ' '.join('{%d,%d},' % p for p in pts[i:i + 8]))
print('};\n')
print('/* Ring k: points world_map_rings[k] .. world_map_rings[k + 1] - 1 */')
print('static const uint16_t world_map_rings[] = {')
starts, s = [], 0
for r in rings:
    starts.append(s)
    s += len(r)
starts.append(s)
for i in range(0, len(starts), 16):
    print('    ' + ' '.join('%d,' % v for v in starts[i:i + 16]))
print('};')
print('#define WORLD_MAP_RINGS %d' % len(rings))
